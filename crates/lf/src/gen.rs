//! `cargo cell gen`: TypeScript from the same contract tokens. Each view gets a client with exactly the ops it
//! declares (data, tries, streams), its slot openers with the child's prop types, and the event names it speaks.
use lf_contract::{parse_types, ts_type, TypeDef};
use serde_json::Value;
use std::fmt::Write;

pub fn dir_of(api: &str) -> Option<&'static str> {
    Some(match api {
        "notes" => "notes",
        "status" => "status",
        "trend" => "trend",
        "faults" => "faults",
        "ops" => "ops",
        "systems.catalog" => "systems",
        "fe.history" => "timeline",
        "fe.explain" => "inspect",
        _ => return None,
    })
}

pub fn file_of(d: &Value) -> String {
    format!("{}_{}_{}.ts", d["api"].as_str().unwrap().replace('.', "_"), d["major"], d["minor"])
}

fn ts_def(t: &TypeDef) -> String {
    match t {
        TypeDef::Struct { name, fields } => {
            let f: Vec<String> = fields.iter().map(|(n, ty)| format!("  {n}: {};", ts_type(ty))).collect();
            format!("export interface {name} {{\n{}\n}}\n", f.join("\n"))
        }
        TypeDef::Enum { name, variants } => {
            let v: Vec<String> = variants
                .iter()
                .map(|(n, fields, inner)| match (fields, inner) {
                    (Some(f), _) => format!("{{ {n}: {{ {} }} }}", f.iter().map(|(k, t)| format!("{k}: {}", ts_type(t))).collect::<Vec<_>>().join("; ")),
                    (None, Some(i)) => format!("{{ {n}: {} }}", ts_type(i)),
                    _ => format!("\"{n}\""),
                })
                .collect();
            format!("export type {name} = {};\n", v.join(" | "))
        }
    }
}

pub fn ts(d: &Value, all: &[Value]) -> String {
    let api = d["api"].as_str().unwrap();
    let mut s = String::new();
    let _ = writeln!(s, "// Generated by `cargo cell gen` from {api}@{}.{} (schema {}). Do not edit.", d["major"], d["minor"], d["schema"].as_str().unwrap());
    let _ = writeln!(s, "import type {{ Ctx }} from '../../../../web/cell-rt';\n");
    let _ = writeln!(s, "export const API = '{api}@{}';\nexport const VERSION = '{}.{}';\nexport const SCHEMA = '{}';\n", d["major"], d["major"], d["minor"], d["schema"].as_str().unwrap());
    let types = parse_types(d["types"].as_str().unwrap_or(""));
    for t in &types {
        s.push_str(&ts_def(t));
    }
    let ops = d["ops"].as_array().unwrap();
    for v in d["views"].as_array().unwrap() {
        let list = |k: &str| -> Vec<String> { v[k].as_array().unwrap().iter().map(|x| x.as_str().unwrap().to_string()).collect() };
        let mut names = list("data");
        names.extend(list("tries"));
        names.extend(list("streams"));
        let _ = writeln!(s, "\n/** The ops view `{}` may call: data {:?}, tries {:?} (may be refused), streams {:?}. */", v["name"].as_str().unwrap(), list("data"), list("tries"), list("streams"));
        let _ = writeln!(s, "export interface Client {{");
        for o in ops.iter().filter(|o| names.contains(&o["name"].as_str().unwrap().to_string())) {
            let req = o["req"].as_str().unwrap();
            let arg = if req == "()" { String::new() } else { format!("b: {}", ts_type(req)) };
            let _ = writeln!(s, "  {}({arg}): Promise<{}>;", o["name"].as_str().unwrap(), ts_type(o["resp"].as_str().unwrap()));
        }
        let _ = writeln!(s, "}}\nexport function client(cx: Ctx): Client {{\n  return {{");
        for o in ops.iter().filter(|o| names.contains(&o["name"].as_str().unwrap().to_string())) {
            let (n, req) = (o["name"].as_str().unwrap(), o["req"].as_str().unwrap());
            if req == "()" {
                let _ = writeln!(s, "    {n}: () => cx.call('{n}', null),");
            } else {
                let _ = writeln!(s, "    {n}: (b) => cx.call('{n}', b),");
            }
        }
        let _ = writeln!(s, "  }};\n}}");
        // slots: the child's props type, copied from the child's contract
        let slots = v["slots"].as_array().unwrap();
        let mut child_types = String::new();
        let _ = writeln!(s, "export interface Slots {{");
        for sl in slots {
            let props = sl["props"].as_str().unwrap();
            let _ = writeln!(s, "  {}(p: {props}): void;", sl["name"].as_str().unwrap());
            let child = all.iter().find(|c| c["views"].as_array().unwrap().iter().any(|cv| cv["render"] == sl["render"]));
            if let Some(c) = child {
                if let Some(t) = parse_types(c["types"].as_str().unwrap_or("")).into_iter().find(|t| t.name() == props) {
                    if !types.iter().any(|x| x.name() == props) {
                        child_types.push_str(&ts_def(&t));
                    }
                }
            }
        }
        let _ = writeln!(s, "}}\nexport function slots(cx: Ctx): Slots {{\n  return {{");
        for sl in slots {
            let _ = writeln!(s, "    {0}: (p) => cx.slot('{0}', p),", sl["name"].as_str().unwrap());
        }
        let _ = writeln!(s, "  }};\n}}");
        s.push_str(&child_types);
        let speaks: Vec<String> = list("speaks").iter().map(|e| format!("'{e}'")).collect();
        let _ = writeln!(s, "export type Speaks = {};", if speaks.is_empty() { "never".into() } else { speaks.join(" | ") });
        let props = v["props"].as_str().unwrap();
        let _ = writeln!(s, "export type Props = {};", if props == "()" { "null".to_string() } else { props.to_string() });
        let st = v["state"].as_str().unwrap();
        let _ = writeln!(s, "export type State = {};", if st == "()" { "null".to_string() } else { st.to_string() });
    }
    s
}

/// Writes every generated file; returns the paths written.
pub fn run(root: &std::path::Path) -> Vec<String> {
    let all = fe_host::registry::all();
    let mut wrote = vec![];
    for d in all.iter() {
        let Some(dir) = dir_of(d["api"].as_str().unwrap()) else { continue };
        if d["views"].as_array().unwrap().is_empty() {
            continue;
        }
        let p = root.join(format!("cells/{dir}/ui/gen/{}", file_of(d)));
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        let text = ts(d, all);
        if std::fs::read_to_string(&p).ok().as_deref() != Some(&text) {
            std::fs::write(&p, &text).unwrap();
        }
        wrote.push(p.strip_prefix(root).unwrap().display().to_string());
    }
    wrote
}
